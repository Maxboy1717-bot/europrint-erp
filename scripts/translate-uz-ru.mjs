// ------- The translator -------
function fixCase(translated, original) {
  // If original is fully uppercase, uppercase translation
  if (original === original.toUpperCase() && /[A-Z]/.test(original)) {
    // Probably acronym; skip
  }
  // If original starts uppercase, ensure translation starts uppercase
  if (/^[A-ZА-ЯЁ]/.test(original.trim()) && /^[а-яё]/.test(translated)) {
    return translated.charAt(0).toUpperCase() + translated.slice(1);
  }
  return translated;
}

function translateWord(w) {
  if (!w) return w;
  // Strip surrounding punctuation
  const m = w.match(/^([^A-Za-zА-Яа-яЁё0-9'']*)([\s\S]*?)([^A-Za-zА-Яа-яЁё0-9'']*)$/);
  const pre = m ? m[1] : '';
  const core = m ? m[2] : w;
  const post = m ? m[3] : '';
  if (!core) return w;

  // Preserved tokens
  if (KEEP_TOKENS.has(core) || KEEP_TOKENS.has(core.toUpperCase())) return pre + core + post;
  if (BRANDS.has(core) || [...BRANDS].some(b => b.toLowerCase() === core.toLowerCase())) return pre + core + post;

  // Number or numeric+unit
  if (/^\d+$/.test(core)) return pre + core + post;
  if (/^\d+[%]?$/.test(core)) return pre + core + post;

  // Already Russian
  if (hasCyrillic(core)) return pre + core + post;

  const lower = core.toLowerCase();
  const normLower = norm(lower);

  const hit = WORD_MAP.get(normLower);
  if (hit) {
    // Preserve initial capital
    let out = hit;
    if (/^[A-ZА-ЯЁ]/.test(core)) {
      out = out.charAt(0).toUpperCase() + out.slice(1);
    }
    return pre + out + post;
  }

  return pre + core + post;
}

function translateString(orig) {
  const original = orig;
  if (!original) return original;

  // Skip rules
  if (hasCyrillic(original)) return original;
  if (isExpression(original)) return original;
  if (isIdLike(original)) return original;

  // Phrase-level exact match (lowercase, normalized apostrophe)
  const phraseKey = norm(original).toLowerCase().trim();
  const phraseHit = PHRASE_MAP.get(phraseKey);
  if (phraseHit) {
    return phraseHit;
  }

  // Also try without trailing punctuation
  const m = original.match(/^([\s\S]*?)([\s\.\,\!\?\:\;\…\*•]+)$/);
  if (m) {
    const baseKey = norm(m[1]).toLowerCase().trim();
    const baseHit = PHRASE_MAP.get(baseKey);
    if (baseHit) {
      return baseHit + m[2];
    }
  }

  // Word-by-word fallback. Preserve emojis and existing latin tokens.
  // Split keeping whitespace and punctuation positions.
  const tokens = original.split(/(\s+|[.,!?:;\(\)\[\]•—–…"]|—|–|…|\*)/);
  let translated = tokens.map(t => {
    if (!t) return t;
    if (/^\s+$/.test(t)) return t;
    if (/^[.,!?:;\(\)\[\]•—–…"\*—–…]+$/.test(t)) return t;
    // Emoji etc?
    if (/[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/u.test(t)) return t;
    // Numbers
    if (/^\d/.test(t)) return t;
    return translateWord(t);
  }).join('');

  return translated;
}

// ------- Main -------
const data = JSON.parse(fs.readFileSync(INPUT, 'utf8'));

const out = {};
let stats = { total: 0, alreadyRu: 0, codeLike: 0, idLike: 0, phraseHit: 0, wordTranslated: 0, untouched: 0 };

for (const entry of data) {
  stats.total++;
  const k = entry.k;
  const v = entry.v;

  if (hasCyrillic(v)) {
    out[k] = v;
    stats.alreadyRu++;
    continue;
  }
  if (isExpression(v)) {
    out[k] = v;
    stats.codeLike++;
    continue;
  }
  if (isIdLike(v)) {
    out[k] = v;
    stats.idLike++;
    continue;
  }

  const translated = translateString(v);
  out[k] = translated;
  if (translated === v) stats.untouched++;
  else stats.wordTranslated++;
}

fs.writeFileSync(OUTPUT, JSON.stringify(out, null, 2), 'utf8');
console.log('Stats:', stats);
