// Detection helpers
function hasCyrillic(s) { return /[А-Яа-яЁё]/.test(s); }
function isExpression(s) {
  // TypeScript/JS-like
  return /[(){}=]|\|\||\?:|=>|\.length\b|\\u[0-9a-f]{4}/.test(s);
}
function isIdLike(s) {
  const t = s.trim();
  if (/\s/.test(t)) return false;
  if (/^[a-z][a-z0-9_-]*$/i.test(t) && t.length > 1) {
    // Things like 'material-id', 'vendor-001', 'EXTERNAL_IN', 'blocked_by_material'
    if (/[-_]/.test(t) || /^[A-Z][A-Z0-9_]+$/.test(t)) return true;
  }
  if (/^[A-Z][A-Z0-9_]+$/.test(t)) return true;
  if (/^[a-z]+-\d+$/i.test(t)) return true;
  return false;
}

