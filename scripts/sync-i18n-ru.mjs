// ─── Translator ─────────────────────────────────────────────────────────────

function translateUzToRu(uzText) {
  if (typeof uzText !== 'string' || uzText.length === 0) return uzText;
  // Exact match first
  if (PHRASES.has(uzText)) return PHRASES.get(uzText);
  // Word-by-word with capitalization preservation for first letter
  const words = uzText.split(/(\s+|[/.,:;!?()])/);
  let any = false;
  const out = words.map((w) => {
    if (!/\S/.test(w)) return w;
    const trimmed = w;
    if (PHRASES.has(trimmed)) { any = true; return PHRASES.get(trimmed); }
    if (WORDS.has(trimmed)) { any = true; return WORDS.get(trimmed); }
    const lower = trimmed.toLowerCase();
    if (WORDS.has(lower)) { any = true; return WORDS.get(lower); }
    return w;
  });
  return any ? out.join('') : uzText;
}

// ─── Main: sync each module ────────────────────────────────────────────────

const modules = readdirSync(UZ).filter((f) => f.endsWith('.json')).map((f) => f.replace(/\.json$/, ''));
const summary = { modules: 0, keysAdded: 0, englishFixed: 0, filesUpdated: [] };

for (const mod of modules) {
  const uzPath = join(UZ, `${mod}.json`);
  const ruPath = join(RU, `${mod}.json`);
  const uz = JSON.parse(readFileSync(uzPath, 'utf-8'));
  const ru = JSON.parse(readFileSync(ruPath, 'utf-8'));
  let added = 0, fixed = 0;

  // 1. Add missing keys
  for (const [k, v] of Object.entries(uz)) {
    if (!(k in ru)) {
      ru[k] = translateUzToRu(v);
      added++;
    }
  }

  // 2. Re-translate previously-untranslated keys (where RU still equals UZ).
  //    This catches dictionary expansions in subsequent runs.
  let retranslated = 0;
  for (const [k, v] of Object.entries(ru)) {
    if (typeof v !== 'string') continue;
    if (uz[k] === v && !/[Ѐ-ӿ]/.test(v)) {
      const next = translateUzToRu(v);
      if (next !== v) {
        ru[k] = next;
        retranslated++;
      }
    }
  }
  fixed += retranslated;

  // 3. Fix English-stuck RU values
  for (const [k, v] of Object.entries(ru)) {
    if (typeof v === 'string' && ENGLISH_RU_FIXES.has(v)) {
      ru[k] = ENGLISH_RU_FIXES.get(v);
      fixed++;
    }
  }

  if (added > 0 || fixed > 0) {
    writeFileSync(ruPath, JSON.stringify(ru, null, 2) + '\n', 'utf-8');
    summary.filesUpdated.push({ mod, added, fixed });
    summary.modules++;
    summary.keysAdded += added;
    summary.englishFixed += fixed;
  }
}

