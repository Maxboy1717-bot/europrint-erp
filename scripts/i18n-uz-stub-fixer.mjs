// =======================================================================
// 3. Camel-case splitter — fallback when key is not in glossary
// =======================================================================
function splitCamel(s) {
  return s
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2')
    .split(/[\s_]+/)
    .filter(Boolean);
}

function titleCase(s) {
  if (!s) return s;
  return s.charAt(0).toUpperCase() + s.slice(1);
}

// =======================================================================
// 4. Stub detection — exactly matches the audit
// =======================================================================
function isStub(leaf, value) {
  if (typeof value !== 'string') return false;
  if (value.length === 0) return false;
  if (WHITELIST.has(value)) return false;
  if (value === leaf) return true;
  if (!value.includes(' ') && value.toLowerCase() === leaf.toLowerCase()) return true;
  return false;
}

// =======================================================================
// 5. Translate
// =======================================================================
function translate(leaf, value) {
  if (WHITELIST.has(value) || WHITELIST.has(value.toUpperCase())) return null;

  const lower = leaf.toLowerCase();

  // Direct dictionary
  if (UZ[lower]) {
    const tr = UZ[lower];
    // If single-word translation still matches the leaf case-insensitively,
    // the audit will continue to flag it. Skip — we cannot improve.
    if (!tr.includes(' ') && tr.toLowerCase() === lower) return null;
    return tr;
  }
  if (UZ[value.toLowerCase()]) {
    const tr = UZ[value.toLowerCase()];
    if (!tr.includes(' ') && tr.toLowerCase() === lower) return null;
    return tr;
  }

  // Prefix patterns
  const camel = splitCamel(leaf);
  if (camel.length >= 2) {
    const head = camel[0].toLowerCase();
    const restRaw = camel.slice(1).map(w => w.toLowerCase()).join(' ');
    const rest = restRaw.replace(/\s+/g, ' ').trim();
    const restCap = titleCase(rest);

    // Suffix patterns first
    const tail = camel[camel.length - 1].toLowerCase();
    const headRaw = camel.slice(0, -1).map(w => w.toLowerCase()).join(' ');
    const headCap = titleCase(headRaw);
    const tailMap = {
      'count':    `${headCap} soni`,
      'total':    `${headCap} jami`,
      'loading':  `${headCap} yuklanmoqda`,
      'required': `${headCap} majburiy`,
      'failed':   `${headCap} muvaffaqiyatsiz`,
      'success':  `${headCap} muvaffaqiyatli`,
      'list':     `${headCap} ro'yxati`,
      'date':     `${headCap} sanasi`,
      'time':     `${headCap} vaqti`,
      'name':     `${headCap} nomi`,
      'type':     `${headCap} turi`,
      'status':   `${headCap} holati`,
      'amount':   `${headCap} miqdori`,
      'price':    `${headCap} narxi`,
      'quantity': `${headCap} miqdori`,
      'description': `${headCap} tavsifi`,
      'value':    `${headCap} qiymati`,
      'rate':     `${headCap} stavkasi`,
      'percent':  `${headCap} foizi`,
      'percentage': `${headCap} foizi`,
    };
    if (tailMap[tail]) return tailMap[tail];

    const prefixMap = {
      'new':    `Yangi ${rest}`,
      'edit':   `${restCap} tahrirlash`,
      'create': `${restCap} yaratish`,
      'delete': `${restCap} o'chirish`,
      'add':    `${restCap} qo'shish`,
      'update': `${restCap} yangilash`,
      'save':   `${restCap} saqlash`,
      'search': `${restCap} qidirish`,
      'show':   `${restCap} ko'rsatish`,
      'hide':   `${restCap} yashirish`,
      'total':  `Jami ${rest}`,
    };
    if (prefixMap[head]) return prefixMap[head];

    // Default: just convert camelCase -> space-separated lowercase phrase
    return titleCase(camel.map(w => w.toLowerCase()).join(' '));
  }

  // Single-word lowercase fallback: title-case it (audit still flags but UI ok)
  if (/^[a-z][a-z0-9]*$/.test(value)) {
    return titleCase(value);
  }

  return null;
}

// =======================================================================
// 6. Tree walker
// =======================================================================
function walk(obj, onLeaf, prefix = '') {
  for (const k of Object.keys(obj)) {
    const v = obj[k];
    const fullKey = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      walk(v, onLeaf, fullKey);
    } else if (typeof v === 'string') {
      const leaf = fullKey.split('.').pop();
      const replaced = onLeaf(leaf, v, fullKey);
      if (replaced !== undefined && replaced !== null) {
        obj[k] = replaced;
      }
    }
  }
}

function flatPaths(obj, prefix = '', out = new Map()) {
  for (const k of Object.keys(obj)) {
    const v = obj[k];
    const fullKey = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      flatPaths(v, fullKey, out);
    } else {
      out.set(fullKey, v);
    }
  }
  return out;
}

// =======================================================================
// 7. Process directories
// =======================================================================
let stubsBefore = 0;
let stubsAfter = 0;
let convertedTotal = 0;
let glossaryHits = 0;
let camelHits = 0;
let titleHits = 0;
const filesChanged = [];

function countStubs(obj) {
  let n = 0;
  for (const [k, v] of flatPaths(obj)) {
    if (typeof v === 'string' && isStub(k.split('.').pop(), v)) n++;
  }
  return n;
}

function processDir(dir, mirror) {
  for (const fn of fs.readdirSync(dir)) {
    if (!fn.endsWith('.json')) continue;
    const uzPath = path.join(dir, fn);
    const ruPath = mirror ? path.join(mirror, fn) : null;
    const uz = JSON.parse(fs.readFileSync(uzPath, 'utf-8'));
    let ru = null;
    if (ruPath && fs.existsSync(ruPath)) {
      try { ru = JSON.parse(fs.readFileSync(ruPath, 'utf-8')); }
      catch { ru = null; }
    }

    const before = countStubs(uz);
    stubsBefore += before;

    let changed = 0;
    walk(uz, (leaf, value) => {
      if (!isStub(leaf, value)) return undefined;
      const next = translate(leaf, value);
      if (next == null || next === value) return undefined;
      changed++;
      const lower = leaf.toLowerCase();
      if (UZ[lower] === next) glossaryHits++;
      else if (next.includes(' ')) camelHits++;
      else titleHits++;
      return next;
    });
    convertedTotal += changed;

    // Mirror RU file:
    if (ru) {
      walk(ru, (leaf, value) => {
        if (!isStub(leaf, value)) return undefined;
        if (/^[A-Z]/.test(value) && value === leaf) return undefined;
        // Title-case only — RU translation should be done separately.
        return titleCase(value);
      });
      fs.writeFileSync(ruPath, JSON.stringify(ru, null, 2) + '\n', 'utf-8');
    }

    fs.writeFileSync(uzPath, JSON.stringify(uz, null, 2) + '\n', 'utf-8');

    const after = countStubs(uz);
    stubsAfter += after;
    if (changed > 0) filesChanged.push({ fn, before, after, changed });
  }
}

